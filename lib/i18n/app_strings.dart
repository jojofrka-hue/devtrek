/// Every user-facing string lives here. Missing keys fall back to English,
/// and Arabic content switches [MaterialApp] to RTL automatically.
class AppStrings {
  const AppStrings(this.localeCode);

  final String localeCode;

  bool get isArabic => localeCode == 'ar';

  static AppStrings of(BuildContext context) =>
      AppStrings(Localizations.localeOf(context).languageCode);

  String t(String key) {
    final map = isArabic ? _ar : _en;
    return map[key] ?? _en[key] ?? key;
  }
}

